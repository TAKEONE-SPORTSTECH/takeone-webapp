#!/usr/bin/env bash
#
# Ship it: staging → production in one command.
#
#   scripts/ship.sh "commit message"     commit what is here, push, deploy
#   scripts/ship.sh --dry-run            say what would happen, change nothing
#   scripts/ship.sh                      nothing to commit? ship what is pushed
#   scripts/ship.sh --uploads-only       only copy uploaded files production lacks
#
# The staging box is where the code is written, so it is the SOURCE of a
# release, never a deploy target. This script:
#   1. checks the production runner is online (else nothing is pushed),
#   2. refuses secrets and personal documents (the GitHub repo is PUBLIC),
#   3. commits everything here and pushes the current branch,
#   4. fast-forwards main to it — never a force push, never a merge,
#   5. runs the Deploy workflow (backup → code archive → maintenance →
#      sync → migrate → caches → site check) and waits for the result,
#   6. copies every uploaded file (photos, logos, proofs, bout video) that
#      production does not have yet — a deploy carries code, never uploads.
#
# Nothing on this box is deleted or reset by it, and the uploads copy only
# ever ADDS files on production: never an overwrite, never a delete.

set -euo pipefail

REPO=TAKEONE-SPORTSTECH/takeone-webapp
cd "$(dirname "$0")/.."

dry=0
uploads_only=0
msg=""
for arg in "$@"; do
    case "$arg" in
        --dry-run) dry=1 ;;
        --uploads-only) uploads_only=1 ;;
        -*) echo "Unknown option: $arg" >&2; exit 2 ;;
        *) msg="$arg" ;;
    esac
done

say()  { printf '\n\033[1m%s\033[0m\n' "$*"; }
fail() { printf '\n\033[31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

# ── Uploads: copy what production does not have yet ─────────────────────
# A deploy carries code and nothing under storage/, so a photo, logo, proof or
# bout video uploaded here never reached production on its own (2026-10-30:
# 1,412 files were missing). This adds the files production lacks, over SSH:
# --ignore-existing (never overwrites production's copy), no --delete (never
# removes anything), owned by the deploy user so its backup can read them.
# Left behind: this box's own backups and scratch, cache/ (thumbnails and cards
# each box regenerates by itself), PHP files (storage must
# never carry code), and old APK backups. When UPLOADS_ROOT is set, both boxes
# already read one shared folder, so there is nothing to copy.
PROD_SSH=${PROD_SSH:-takeone-live}
PROD_UPLOADS=/var/www/takeone/storage/app
sync_uploads() {
    if grep -qE '^UPLOADS_ROOT=.+' .env; then
        echo "  UPLOADS_ROOT is set — both boxes share one uploads folder; nothing to copy."
        return 0
    fi
    local extra=()
    [ "$dry" = 1 ] && extra=(--dry-run)
    local out
    out=$(rsync -rlt --ignore-existing --chown=actionsrunner:actionsrunner --chmod=D2775,F664 \
        --exclude='/backups/' --exclude='/private/' --exclude='/sim/' --exclude='/temp/' --exclude='/cache/' \
        --exclude='/livewire-tmp/' --exclude='/demo/' --exclude='/tv/*.bak*' \
        --exclude='*.php' --exclude='*.part' --exclude='.gitignore' \
        --stats "${extra[@]}" -e ssh storage/app/ "$PROD_SSH:$PROD_UPLOADS/") \
        || return 1
    echo "$out" | grep -E '^(Number of regular files transferred|Total transferred file size)' | sed 's/^/  /'
}

if [ "$uploads_only" = 1 ]; then
    say "Copying uploads production does not have yet"
    [ "$dry" = 1 ] && echo "  (dry run — nothing is copied)"
    sync_uploads || fail "The uploads copy failed."
    exit 0
fi

branch=$(git rev-parse --abbrev-ref HEAD)
[ "$branch" = "HEAD" ] && fail "Detached HEAD — check out a branch first."

# ── 1. Production runner ────────────────────────────────────────────────
say "Checking the production runner"
online=$(gh api "repos/$REPO/actions/runners" \
    --jq '[.runners[] | select(.status=="online") | select(any(.labels[]; .name=="production"))] | length')
[ "$online" -ge 1 ] || fail "No production runner is online, so a deploy would only queue and time out. Nothing was pushed."
echo "  online"

# ── 1b. Feature switches: whatever is on here is on in production ───────
# The owner's rule (2026-10-30): everything shipped is ON in production. The
# switches live in .env, which a deploy never copies, so every on/off switch
# in this box's .env is written to deploy/feature-flags.conf, shipped with the
# release, and applied to production's .env by deploy.yml. Only true/false
# values travel (plus the few named enum switches below) — never a secret,
# URL or host. Keys that describe THIS SERVER, not a feature, are left out.
FLAGS_FILE=deploy/feature-flags.conf
SERVER_KEYS='^(APP|DB|MAIL|CACHE|SESSION|QUEUE|LOG|BACKUP|BROADCAST|REDIS|FILESYSTEM|VITE|AWS|PUSHER|REVERB)_|^FILE_XSENDFILE(=|$)|DEBUG|^(TELESCOPE|IGNITION|DEBUGBAR|CLOCKWORK|PULSE|NIGHTWATCH|SENTRY|SANCTUM|CORS|HORIZON)_|CAPTCHA|2FA|TWO_FACTOR|VERIF|THROTTLE|TRUST'
ENUM_KEYS='^(NEW_UI|PARTIES_AUTHORITY)$'
flags_tmp=$(mktemp)
{
    echo "# Generated by scripts/ship.sh from the staging .env — do not edit by hand."
    echo "# Applied to production's .env by .github/workflows/deploy.yml on every ship."
    sed -E 's/[[:space:]]+#.*$//; s/^[[:space:]]+|[[:space:]]+$//g' .env \
        | grep -E '^[A-Z][A-Z0-9_]*=' \
        | grep -vE "$SERVER_KEYS" \
        | awk -F= -v enum="$ENUM_KEYS" '{
              k=$1; v=substr($0, length(k)+2); gsub(/^["'\'']|["'\'']$/, "", v); lv=tolower(v)
              if (lv=="true" || lv=="false") print k "=" lv
              else if (k ~ enum && v ~ /^[a-z0-9_-]+$/) print k "=" v
          }' \
        | sort -u
} > "$flags_tmp"
echo "  $(grep -vc '^#' "$flags_tmp") feature switches for production"
if [ "$dry" = 1 ]; then rm -f "$flags_tmp"
else mkdir -p deploy && mv "$flags_tmp" "$FLAGS_FILE" && chmod 644 "$FLAGS_FILE"; fi

# ── 2. What would be committed, and is any of it unsafe to publish ──────
changes=$(git status --porcelain --untracked-files=all)
if [ -n "$changes" ]; then
    say "Changes to commit: $(echo "$changes" | wc -l) files"
    files=$(echo "$changes" | cut -c4- | sed 's/^"\(.*\)"$/\1/; s/.* -> //')

    risky=$(echo "$files" | grep -E \
        '(^|/)\.env($|\.)|\.sqlite|\.jks$|\.keystore$|keystore\.properties$|\.pem$|\.key$|\.api-key$|(^|/)id_(rsa|ed25519)|^drafts/.*\.(pdf|docx?|xlsx?|zip|jpe?g|png|heic)$' \
        | grep -v '^\.env\.example$' || true)
    [ -z "$risky" ] || fail "These look like secrets or personal documents, and the repository is PUBLIC:
$(echo "$risky" | sed 's/^/    /')
Add them to .gitignore (or move them out of the project), then ship again. Nothing was committed."

    secrets=$(git diff HEAD -U0 2>/dev/null | grep -E '^\+' \
        | grep -E 'sk-ant-[A-Za-z0-9_-]{20,}|gh[pousr]_[A-Za-z0-9]{30,}|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY' || true)
    [ -z "$secrets" ] || fail "A changed line looks like an API key or private key. Nothing was committed."

    [ -n "$msg" ] || fail "There are uncommitted changes — give a commit message: scripts/ship.sh \"what changed\""
else
    say "Nothing to commit — shipping what is already on $branch"
fi

# ── 3. main must be an ancestor, so main only ever moves forward ────────
git fetch -q origin
if ! git merge-base --is-ancestor origin/main HEAD; then
    fail "main has commits that $branch does not (git log HEAD..origin/main). Merge main into $branch first. Nothing was pushed."
fi

if [ "$dry" = 1 ]; then
    say "Uploads production does not have yet (would be copied after the deploy)"
    sync_uploads || echo "  could not check the uploads (SSH to $PROD_SSH failed?)"
    say "Dry run — would commit, push $branch, fast-forward main by $(git rev-list --count origin/main..HEAD) commit(s) plus the new one, run Deploy, and copy the uploads."
    exit 0
fi

# ── 4. Commit and push ──────────────────────────────────────────────────
if [ -n "$changes" ]; then
    say "Committing"
    git add -A
    git commit -q -m "$msg"
    git log --oneline -1
fi

say "Pushing $branch and fast-forwarding main"
git push -q origin "HEAD:refs/heads/$branch"
git push -q origin HEAD:main
echo "  main is now $(git rev-parse --short HEAD)"

# ── 5. Deploy and wait ──────────────────────────────────────────────────
say "Starting the production deploy"
before=$(date -u +%Y-%m-%dT%H:%M:%SZ)
gh workflow run Deploy --repo "$REPO" --ref main
run=""
for _ in $(seq 1 20); do
    run=$(gh run list --repo "$REPO" --workflow Deploy --limit 1 \
        --json databaseId,createdAt --jq ".[] | select(.createdAt >= \"$before\") | .databaseId")
    [ -n "$run" ] && break
    sleep 3
done
[ -n "$run" ] || fail "The deploy did not start. Check: gh run list --workflow Deploy"

echo "  https://github.com/$REPO/actions/runs/$run"
gh run watch "$run" --repo "$REPO" --exit-status --interval 10 > /dev/null || true
# `gh run watch` also gives up on a GitHub 502 while the run is still going
# (2026-10-30), so the run's own conclusion decides, not the watcher's exit.
result=""
for _ in $(seq 1 60); do
    result=$(gh run view "$run" --repo "$REPO" --json status,conclusion \
        --jq 'if .status == "completed" then .conclusion else "" end' 2>/dev/null || true)
    [ -n "$result" ] && break
    sleep 10
done
if [ "$result" = "success" ]; then
    say "✓ Shipped. takeone.bh is running $(git rev-parse --short HEAD)."
else
    gh run view "$run" --repo "$REPO" --log-failed | tail -40 || true
    fail "The deploy failed (log above). The site may be in maintenance mode; the run log says where the backup and code archive are. Uploads were not copied."
fi

# ── 6. Uploads ──────────────────────────────────────────────────────────
say "Copying uploads production does not have yet"
sync_uploads || fail "The code is live, but the uploads copy failed. Re-run: scripts/ship.sh --uploads-only"
