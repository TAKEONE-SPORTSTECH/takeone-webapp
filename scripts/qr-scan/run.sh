#!/usr/bin/env bash
# Runs the QR scan test and rewrites resources/js/islands/designer/qr/risky.js
# (the combinations the QR style panel warns about). Fails if any preset or
# gradient code does not decode. Needs: node_modules (jsqr, esbuild), chromium.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
"$ROOT/node_modules/.bin/esbuild" "$ROOT/scripts/qr-scan/scan.jsx" --bundle --format=iife --jsx=automatic \
    --define:process.env.NODE_ENV='"production"' --log-level=warning --outfile="$WORK/scan.js"
echo '<!doctype html><meta charset=utf-8><body><script src="scan.js"></script>' > "$WORK/scan.html"
CHROME="${CHROME:-$(command -v chromium || command -v chromium-browser || command -v google-chrome)}"
timeout 900 "$CHROME" --headless=new --no-sandbox --disable-gpu --allow-file-access-from-files \
    --virtual-time-budget=1200000 --dump-dom "file://$WORK/scan.html" 2>/dev/null \
    | sed -n 's:.*<pre id="result">\(.*\)</pre>.*:\1:p' > "$WORK/result.json"
php -r '
$r = json_decode(file_get_contents($argv[1]), true);
if (! is_array($r)) { fwrite(STDERR, "The scan page produced no result.\n"); exit(2); }
$js = "/**\n * GENERATED by scripts/qr-scan/run.sh — do not edit. body|frame|centre\n"
    ." * combinations that failed to decode in the scan test ({$r["total"]} codes, ".date("Y-m-d").").\n"
    ." * The QR style panel warns before one of these is used.\n */\n"
    ."export const RISKY = new Set(".json_encode($r["risky"], JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT).");\n";
file_put_contents($argv[2], $js);
echo "Scanned {$r["total"]} codes: ".count($r["risky"])." risky combinations, ".count($r["broken"])." broken presets/gradients.\n";
foreach ($r["broken"] as $b) { echo "  BROKEN: $b\n"; }
exit($r["broken"] ? 1 : 0);
' "$WORK/result.json" "$ROOT/resources/js/islands/designer/qr/risky.js"
